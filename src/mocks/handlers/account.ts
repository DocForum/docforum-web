// Account endpoints: data export lifecycle and account deletion.
import { http, HttpResponse } from 'msw';
import { db } from '../db';
import { respond } from '../helpers';
import { PATIENT_PROFILE_ID } from '../fixtures';
import { useMockStore } from '../mock-store';
import type { DataExport } from '../../types/models';

export const accountHandlers = [
  http.post(
    '*/account/data-export',
    respond('json', () => {
      const now = new Date();
      const ready: DataExport = {
        id: `exp-mock-${Date.now()}`,
        patientProfileId: PATIENT_PROFILE_ID,
        status: 'ready',
        requestedAt: now.toISOString(),
        readyAt: now.toISOString(),
        expiresAt: new Date(now.getTime() + 24 * 60 * 60 * 1000).toISOString(),
        fileSizeBytes: 20480,
        downloadUrl: null,
        errorMessage: null,
      };
      db.dataExport = ready;
      return ready;
    }),
  ),

  http.get('*/account/data-export', respond('nullable', () => db.dataExport)),

  http.get(
    '*/account/data-export/:id/download',
    async ({ params }) => {
      const { scenario, latencyMs } = useMockStore.getState();
      if (latencyMs > 0) await new Promise((r) => setTimeout(r, latencyMs));
      if (scenario === 'error') {
        return HttpResponse.json(
          { message: 'Mock scenario: forced server error (dev panel)' },
          { status: 500 },
        );
      }
      const payload = {
        note: 'FAKE DATA EXPORT — generated by docforum-web mock API. Contains no real records.',
        exportId: String(params.id),
        generatedAt: new Date().toISOString(),
        profile: { fullName: 'Pat Placeholder (fake)', dateOfBirth: '1990-01-01' },
        allergies: ['Peanuts (fake)'],
        medications: ['Demo Vitamin D 1000 IU (fake)'],
      };
      return new HttpResponse(JSON.stringify(payload, null, 2), {
        headers: {
          'Content-Type': 'application/json',
          'Content-Disposition': 'attachment; filename="docforum-fake-export.json"',
        },
      });
    },
  ),

  http.post(
    '*/account/delete',
    respond('json', () => ({
      success: true,
      message:
        'Mock API: account "deleted" (nothing is persisted — fixtures reset on reload).',
      deletedAt: new Date().toISOString(),
    })),
  ),
];
