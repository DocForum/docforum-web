// Account endpoints: data export lifecycle and account deletion.
import { http, HttpResponse } from 'msw';
import { db } from '../db';
import { notFound, respond } from '../helpers';
import { useMockStore } from '../mock-store';
import type { DataExport } from '../../types/models';

function isReadyToDownload(exportData: DataExport, now = Date.now()): boolean {
  return exportData.status === 'ready' && (!exportData.expiresAt || Date.parse(exportData.expiresAt) > now);
}

export const accountHandlers = [
  // docforum-core's real contract (#40): `POST /patients/me/export` reads no
  // body and answers `202` with the status object plus a `Location` header.
  // If an export is already pending/processing, core returns that one.
  http.post(
    '*/patients/me/export',
    respond('json', async () => {
      const existing = db.dataExport;
      if (existing && (existing.status === 'pending' || existing.status === 'processing')) {
        return new HttpResponse(JSON.stringify(existing), {
          status: 202,
          headers: {
            'Content-Type': 'application/json',
            Location: `/patients/me/export/${existing.id}`,
          },
        });
      }

      const now = new Date();
      const ready: DataExport = {
        id: `exp-mock-${Date.now()}`,
        status: 'ready',
        schemaVersion: 1,
        createdAt: now.toISOString(),
        startedAt: now.toISOString(),
        generatedAt: now.toISOString(),
        expiresAt: new Date(now.getTime() + 24 * 60 * 60 * 1000).toISOString(),
        sizeBytes: 20480,
        failure: null,
        downloadUrl: null,
      };
      db.dataExport = ready;
      return new HttpResponse(JSON.stringify(ready), {
        status: 202,
        headers: {
          'Content-Type': 'application/json',
          Location: `/patients/me/export/${ready.id}`,
        },
      });
    }),
  ),

  http.get(
    '*/patients/me/export/:exportId',
    respond('json', ({ params }) => {
      if (!db.dataExport || db.dataExport.id !== String(params.exportId)) {
        return notFound('export');
      }
      if (db.dataExport.status === 'ready' && !isReadyToDownload(db.dataExport)) {
        db.dataExport.status = 'expired';
      }
      return db.dataExport;
    }),
  ),

  http.get(
    '*/patients/me/export/:exportId/download',
    async ({ params }) => {
      const { scenario, latencyMs } = useMockStore.getState();
      if (latencyMs > 0) await new Promise((r) => setTimeout(r, latencyMs));
      if (scenario === 'error') {
        return HttpResponse.json(
          { message: 'Mock scenario: forced server error (dev panel)' },
          { status: 500 },
        );
      }

      const exportData = db.dataExport;
      if (!exportData || exportData.id !== String(params.exportId)) {
        return notFound('export');
      }
      if (exportData.status === 'expired') {
        return HttpResponse.json(
          { message: 'Export expired.', code: 'EXPORT_EXPIRED' },
          { status: 410 },
        );
      }
      if (!isReadyToDownload(exportData)) {
        if (exportData.status === 'ready') exportData.status = 'expired';
        if (exportData.status === 'expired') {
          return HttpResponse.json(
            { message: 'Export expired.', code: 'EXPORT_EXPIRED' },
            { status: 410 },
          );
        }
        return HttpResponse.json(
          { message: 'Export is not ready yet.', code: 'EXPORT_NOT_READY' },
          { status: 409 },
        );
      }

      const payload = {
        note: 'FAKE DATA EXPORT — generated by docforum-web mock API. Contains no real records.',
        exportId: exportData.id,
        generatedAt: exportData.generatedAt,
        profile: { fullName: 'Pat Placeholder (fake)', dateOfBirth: '1990-01-01' },
        allergies: ['Peanuts (fake)'],
        medications: ['Demo Vitamin D 1000 IU (fake)'],
      };
      return new HttpResponse(JSON.stringify(payload, null, 2), {
        headers: {
          'Content-Type': 'application/json',
          'Content-Disposition': 'attachment; filename="docforum-fake-export.json"',
        },
      });
    },
  ),

  // docforum-core's real contract: `DELETE /patients/me` with `{ password }`,
  // `204 No Content`, and `403 PASSWORD_CONFIRMATION_FAILED` for a wrong
  // password. The mock accepts any password except "wrong-password" (used by
  // the tests to exercise the field-error path); nothing is persisted, so
  // fixtures reset on reload.
  http.delete('*/patients/me', async ({ request }) => {
    const body = (await request.json().catch(() => null)) as { password?: unknown } | null;
    if (!body || typeof body.password !== 'string' || body.password.length === 0) {
      return HttpResponse.json({ message: 'Password is required.' }, { status: 400 });
    }
    if (body.password === 'wrong-password') {
      return HttpResponse.json(
        { message: 'Password confirmation failed.', code: 'PASSWORD_CONFIRMATION_FAILED' },
        { status: 403 },
      );
    }
    return new HttpResponse(null, { status: 204 });
  }),
];
